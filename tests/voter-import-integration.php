<?php
/** Real HTTP import coverage, called only by the isolated integration suite. */
declare(strict_types=1);
return static function(Suite $t, PDO $pdo): void {
    $fx=tdb_seed($pdo); $a=new Http('bulk_admin'); $a->login('t_admin');
    $v=new Http('bulk_voter'); $v->login('t_voter1'); $anon=new Http('bulk_anon');
    $headers=['memberId','first','last','email','phone','address','dob','username'];
    $row=['','Maria','Santos','bulk.maria@test.coop','09171234567',"Purok Uno, Santiago\nIsabela",'1990-01-02',''];
    $csv=static function(array $rows)use($headers):string { $f=fopen('php://temp','r+'); fputcsv($f,$headers,',','"','');foreach($rows as $r)fputcsv($f,$r,',','"','');rewind($f);$out=stream_get_contents($f);fclose($f);return $out; };
    $preview=fn($rows)=>$a->api('POST','voters/import/preview',['csv'=>$csv($rows)]);
    $count=fn()=>(int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
    $t->group('Bulk voter import permissions and election window');
    $t->same('anonymous cannot download template',401,$anon->api('GET','voters/import/template')['status']);
    $t->same('voter cannot import',403,$v->api('POST','voters/import/preview',['csv'=>$csv([$row])])['status']);
    $t->same('active election blocks preview',409,$preview([$row])['status']);
    $pdo->exec("UPDATE elections SET status='closed'");
    $template=$a->api('GET','voters/import/template');
    $t->same('template downloads',200,$template['status']);
    $t->contains('template contains exact headers',implode(',',$headers),$template['body']);
    $excel=$a->api('GET','voters/import/template&format=xlsx');
    $t->same('Excel template downloads',200,$excel['status']);
    $t->same('Excel download is the packaged workbook',hash_file('sha256',BASE_PATH.'/assets/templates/coopvote-voter-template.xlsx'),hash('sha256',$excel['body']));
    $t->contains('Excel uses correct content type','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',$excel['headers']);
    $t->contains('Excel uses xlsx filename','coopvote-voter-template.xlsx',$excel['headers']);
    $t->same('voter cannot download Excel template',403,$v->api('GET','voters/import/template&format=xlsx')['status']);
    $t->same('unsupported template format refused',422,$a->api('GET','voters/import/template&format=exe')['status']);
    $t->same('wrong method refused',405,$a->api('GET','voters/import/commit')['status']);
    $t->same('empty import refused',422,$a->api('POST','voters/import/preview',['csv'=>''])['status']);
    $t->same('wrong headers refused',422,$a->api('POST','voters/import/preview',['csv'=>"name,email\nMaria,test@test.coop"])['status']);
    $t->same('oversized file refused',422,$a->api('POST','voters/import/preview',['csv'=>str_repeat('x',262145)])['status']);
    $t->same('over 100 rows refused',422,$preview(array_fill(0,101,$row))['status']);
    $blankRows=$a->api('POST','voters/import/preview',['csv'=>$csv([$row]).str_repeat(",,,,,,,\r\n",100)]);
    $t->same('Excel formatted blank rows are skipped',1,$blankRows['json']['valid']);
    $t->same('blank rows do not produce validation errors',0,$blankRows['json']['invalid']);
    $before=$count(); $r=$preview([$row]); $token=$r['json']['token'];
    $t->same('valid CSV previews',200,$r['status']);
    $t->same('quoted multiline field retained',$row[5],$r['json']['rows'][0]['data']['address']);
    $t->same('leading zero retained',$row[4],$r['json']['rows'][0]['data']['phone']);
    $t->same('preview does not create users',$before,$count());
    $t->same('tampered token refused',410,$a->api('POST','voters/import/commit',['token'=>'forged'])['status']);
    $other=new Http('bulk_other');$other->login('t_admin');
    $t->same('preview token bound to session',410,$other->api('POST','voters/import/commit',['token'=>$token])['status']);
    $pdo->exec("UPDATE elections SET status='published',start_datetime=DATE_SUB(NOW(),INTERVAL 1 DAY),end_datetime=DATE_ADD(NOW(),INTERVAL 1 DAY) WHERE election_id=".$fx['draft']);
    $t->same('election opening after preview blocks commit',409,$a->api('POST','voters/import/commit',['token'=>$token])['status']);
    $t->same('blocked import creates nothing',$before,$count());
    $pdo->exec("UPDATE elections SET status='closed'");

    $t->group('Bulk field validation and duplicate handling');
    $bad=$row;$bad[1]='Maria123';$bad[3]='invalid';$bad[4]='letters';$bad[5]='   ';$bad[6]='2999-01-01';$bad[7]='bad username';
    $r=$preview([$row,$bad]);$t->same('valid and invalid rows separated',1,$r['json']['valid']);
    foreach(['first','email','phone','address','dob','username'] as $field)$t->ok('validates '.$field,isset($r['json']['rows'][1]['errors'][$field]));
    $dup=$row;$dup[0]='MEM-BULK';$dup[7]='bulk.test';
    $r=$preview([$dup,$dup]);$t->same('both duplicate rows blocked',0,$r['json']['valid']);
    foreach(['email','memberId','username'] as $field)$t->ok('duplicate '.$field.' reported',isset($r['json']['rows'][0]['errors'][$field]));
    $existing=$pdo->query("SELECT u.username,u.email,m.member_no FROM users u JOIN members m ON m.user_id=u.user_id LIMIT 1")->fetch();
    $dup[0]=$existing['member_no'];$dup[3]=$existing['email'];$dup[7]=$existing['username'];
    $r=$preview([$dup]);foreach(['email','memberId','username'] as $field)$t->ok('existing '.$field.' refused',isset($r['json']['rows'][0]['errors'][$field]));
    $r=$preview([array_slice($row,0,7)]);$t->ok('missing column reported',isset($r['json']['rows'][0]['errors']['csv']));
    $r=$preview([$bad]);$t->same('no valid rows cannot commit',422,$a->api('POST','voters/import/commit',['token'=>$r['json']['token']])['status']);

    $t->group('Bulk confirmation, credentials, audit and replay');
    $r=$preview([$row,$bad]);$token=$r['json']['token'];
    $created=$a->api('POST','voters/import/commit',['token'=>$token,'rows'=>[$bad]]);
    $t->same('valid rows created',201,$created['status']);
    $t->same('invalid row skipped',$before+1,$count());
    $new=$created['json']['created'][0];
    $t->same('preview data cannot be swapped at commit','Maria Santos',$new['name']);
    $export=$a->api('GET','voters/export');
    $stream=fopen('php://temp','r+');fwrite($stream,preg_replace('/^\xEF\xBB\xBF/','',$export['body']));rewind($stream);
    $t->same('CSV export matches template column order',$headers,fgetcsv($stream,0,',','"',''));
    $exported=null;while(($values=fgetcsv($stream,0,',','"',''))!==false)if(($values[3]??null)===$row[3])$exported=$values;fclose($stream);
    $t->same('CSV export includes all eight correctly mapped values',[$new['memberNo'],$row[1],$row[2],$row[3],$row[4],$row[5],$row[6],$new['username']],$exported);
    $t->ok('ordinary response omits passwords',!isset($new['password']));
    $t->same('mail disabled is accurate','disabled',$new['delivery']);
    $t->same('repeat confirmation succeeds',200,$a->api('POST','voters/import/commit',['token'=>$token])['status']);
    $t->same('repeat confirmation does not duplicate',$before+1,$count());
    $t->same('result survives dialog reload',$new['id'],$a->api('GET','voters/import/status')['json']['created'][0]['id']);
    $credentials=$a->api('GET','voters/import/credentials');
    $lines=preg_split('/\r?\n/',trim($credentials['body']));$values=str_getcsv($lines[1],',','"','');
    $t->same('credentials download works',200,$credentials['status']);
    $t->same('credentials contain generated username',$new['username'],$values[3]);
    $q=$pdo->prepare('SELECT u.password_hash,r.slug FROM users u JOIN roles r ON u.role_id=r.role_id WHERE u.user_id=?');$q->execute([$new['id']]);$stored=$q->fetch();
    $t->ok('temporary password stored hashed',password_verify($values[4],$stored['password_hash']));
    $t->same('only voter role created','voter',$stored['slug']);
    $login=new Http('bulk_new_login');$t->same('imported voter can log in',200,$login->login($new['username'],$values[4])['status']);
    $log=(string)$pdo->query("SELECT description FROM audit_logs WHERE action='member.created' ORDER BY log_id DESC LIMIT 1")->fetchColumn();
    $t->contains('audit names the member','Maria Santos',$log);$t->notContains('audit excludes password',$values[4],$log);
    $t->same('another session cannot download credentials',410,$other->api('GET','voters/import/credentials')['status']);
    $t->same('email endpoint does not claim delivery when disabled','disabled',$a->api('POST','voters/import/email',['token'=>$token,'id'=>$new['id']])['json']['delivery']);
    $a->api('POST','voters/import/clear',[]);
    $t->same('clear removes credentials',410,$a->api('GET','voters/import/credentials')['status']);

    $t->group('Import conflict between preview and confirmation');
    $row[3]='bulk.race@test.coop';$r=$preview([$row]);$token=$r['json']['token'];
    $pdo->prepare('UPDATE users SET email=? WHERE user_id=?')->execute([$row[3],$new['id']]);
    $before=$count();$t->same('new duplicate blocks entire confirmation',409,$a->api('POST','voters/import/commit',['token'=>$token])['status']);
    $t->same('conflict leaves no partial accounts',$before,$count());
    $a->api('POST','voters/import/clear',[]);
    $t->group('Generated identifiers respect supplied identifiers in later rows');
    $auto=$row;$auto[1]='Clara';$auto[2]='Reyes';$auto[3]='bulk.auto@test.coop';
    $supplied=$auto;$supplied[3]='bulk.supplied@test.coop';$supplied[7]='clarareyes';
    $next=(int)$pdo->query("SELECT COALESCE(MAX(CAST(SUBSTRING(member_no,6) AS UNSIGNED)),0)+1 FROM members WHERE member_no LIKE 'COOP-%'")->fetchColumn();
    $supplied[0]=sprintf('coop-%04d',$next);
    $r=$preview([$auto,$supplied]);
    $result=$a->api('POST','voters/import/commit',['token'=>$r['json']['token']]);
    $t->same('supplied and automatic identifiers coexist',201,$result['status']);
    $created=$result['json']['created'];
    $t->same('supplied username is preserved','clarareyes',$created[1]['username']);
    $t->ok('automatic username avoids supplied username',$created[0]['username']!==$created[1]['username']);
    $t->ok('automatic member ID avoids supplied ID case insensitively',strtolower($created[0]['memberNo'])!==strtolower($created[1]['memberNo']));
    $t->same('result retains CSV order',2,$created[0]['row']);
    $a->api('POST','voters/import/clear',[]);
    tdb_seed($pdo);
};
